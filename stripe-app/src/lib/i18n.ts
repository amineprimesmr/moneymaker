export const strings = (locale?: string): Strings => (locale ?? "").toLowerCase().startsWith("fr") ? fr : en;

export const STORE_LABELS: Record<string, string> = {
  app_store: "App Store", apple: "App Store", play_store: "Google Play", google: "Google Play", stripe: "Stripe",
  paddle: "Paddle", amazon: "Amazon", galaxy: "Galaxy Store", roku: "Roku", promotional: "Promo", web: "Web",
};
export const storeLabel = (s: string) => STORE_LABELS[s] ?? s;

export function money(micros: number | null | undefined, currency: string, locale?: string): string {
  const v = (micros ?? 0) / 1e6;
  try { return new Intl.NumberFormat(locale || "fr", { style: "currency", currency, maximumFractionDigits: v >= 1000 ? 0 : 2 }).format(v); }
  catch { return `${v.toFixed(2)} ${currency}`; }
}

export function date(ms: number | null | undefined, locale?: string): string {
  if (!ms) return "—";
  try { return new Intl.DateTimeFormat(locale || "fr", { dateStyle: "medium" }).format(new Date(ms)); }
  catch { return new Date(ms).toISOString().slice(0, 10); }
}
